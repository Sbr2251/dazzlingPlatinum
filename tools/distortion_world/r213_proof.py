def cmd_fallframes():
    sess = boot()
    try:
        approach_to_ceiling(sess)
        # Walk to (44,32) with stone 1 at (44,33): inputs 0..7 to CP2,
        # then U,U (push to (44,32), push to (44,33)).
        drive(sess, solver_faces()[0:8])
        drive(sess, ["U", "U"])
        expect(sess.player_tile() == (44, 10, 32), f"setup tile {sess.player_tile()}")
        # Press U to push the stone into the gap, releasing the moment the
        # player steps onto (44,33) -- a held U would step again onto the
        # (44,34) gap and fall, contaminating the sample.
        sess.emu.press("UP")
        for _ in range(120):
            sess.emu.run(1)
            if sess.player_tile_or_none() == (44, 10, 33):
                break
        sess.emu.release("UP")
        expect(sess.player_tile() == (44, 10, 33), f"push step {sess.player_tile()}")
        # Sample the stone state every frame until it lands.
        frames = []
        seq = []
        for _ in range(80):
            sess.emu.run(1)
            dbg = read_debug(sess)
            seq.append({"frame": sess.emu.frame, "state": dbg["stoneStates"][0],
                        "stone": (dbg["stones"][0]["x"], dbg["stones"][0]["y"], dbg["stones"][0]["z"]),
                        "player": sess.player_tile_or_none()})
            sess.emu.snap(f"fall-{dbg['stoneStates'][0]}", frames)
            if dbg["stoneStates"][0] == 2:
                break
        sess.wait_settled()
        states = [s["state"] for s in seq]
        expect(1 in states, f"no FALLING state sampled: {states}")
        n_fall = states.count(1)
        # 12 engine ticks (DW_STONE_FALL_FRAMES); the actor frame tick
        # runs at ~30 Hz, so 12 ticks span ~22-24 emulator frames.
        expect(18 <= n_fall <= 28, f"FALLING sampled {n_fall} frames, want ~22 (12 ticks)")
        expect(states[-1] == 2, f"stone did not land: {states[-3:]}")
        dbg = read_debug(sess)
        expect((dbg["stones"][0]["x"], dbg["stones"][0]["y"], dbg["stones"][0]["z"]) == (44, 1, 34),
               f"stone landed at {stones_summary(dbg)}, want (44,1,34)")
        sess.strip(frames, str(OUT / "strip_fallframes.png"), title="r213 stone fall")
        save("fallframes.json", {"sampled": seq, "falling_frames_sampled": n_fall})
        print(f"fallframes PASS: FALLING sampled {n_fall} frames, then LANDED at (44,1,34)")
    finally:
        sess.close()


