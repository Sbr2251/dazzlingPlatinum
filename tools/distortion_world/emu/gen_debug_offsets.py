#!/usr/bin/env python3
"""Regenerate tools/distortion_world/emu/dw_debug_offsets.json -- the
field offsets of engine-a's DwPuzzleDebug (include/overlay009/
dw_puzzle.h) -- from the compiled ROM's DWARF (build/main.nef).

dwlib.debug() reads the JSON instead of hardcoding offsets, so the
reader cannot drift from the header: after any change to
DwPuzzleDebug, rebuild (make release) and re-run this script.

Usage:
  python3 tools/distortion_world/emu/gen_debug_offsets.py [--check]

--check regenerates into a temp file and diffs it against the
checked-in JSON, exiting 1 on a mismatch (run it after header changes
and before committing; the JSON is checked in, so a stale JSON fails
loudly instead of silently misreading the debug struct).
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]
HEADER = REPO / "include" / "overlay009" / "dw_puzzle.h"
NEF = REPO / "build" / "main.nef"
OUT = HERE / "dw_debug_offsets.json"

# (json key, DwPuzzleDebug field). ActorPos fields are covered by
# actor_pos_size + the present/surface offsets below.
FIELDS = [
    ("mapHeader", "mapHeader"),
    ("active", "active"),
    ("player", "playerX"),  # x, y, z are consecutive s16s
    ("surface", "surface"),
    ("tileState", "currentTileState"),
    ("groupBits", "groupBits"),
    ("groupDisplayBits", "groupDisplayBits"),
    ("sigilBits", "sigilBits"),
    ("checkpointIndex", "checkpointIndex"),
    ("checkpoint", "checkpointX"),  # x, y, z consecutive s16s
    ("fallCount", "fallCount"),
    ("frameCount", "frameCount"),
    ("slideActive", "slideActive"),
    ("slideDir", "slideDir"),
    ("slideTarget", "slideTargetX"),  # x, y, z consecutive s16s
    ("slideSteps", "slideSteps"),
    ("lastEvent", "lastEvent"),
    ("lastEventFrame", "lastEventFrame"),
    ("lastEventGroup", "lastEventGroup"),
    ("flashFrames", "flashFrames"),
    ("resetGeneration", "resetGeneration"),
    ("stones", "stones"),  # 8 x DwPuzzleActorPos
    ("stoneCount", "stoneCount"),
    ("shadowPhase", "shadowPhase"),
    ("shadow", "shadow"),  # one DwPuzzleActorPos
    ("echo", "echo"),  # one DwPuzzleActorPos
    ("stoneStates", "stoneStates"),  # u8[DW_PUZZLE_MAX_STONES]
    ("size", None),  # sizeof(DwPuzzleDebug)
    ("actorPosSize", "ACTORPOS"),  # sizeof(DwPuzzleActorPos)
    ("actorPosPresent", "ACTORPOS_PRESENT"),
    ("actorPosSurface", "ACTORPOS_SURFACE"),
]


def _gdb_offsets():
    cmds = []
    for key, field in FIELDS:
        if field is None:
            cmds.append("print sizeof(struct DwPuzzleDebug)")
        elif field == "ACTORPOS":
            cmds.append("print sizeof(struct DwPuzzleActorPos)")
        elif field == "ACTORPOS_PRESENT":
            cmds.append("print (int)&((struct DwPuzzleActorPos*)0)->present")
        elif field == "ACTORPOS_SURFACE":
            cmds.append("print (int)&((struct DwPuzzleActorPos*)0)->surface")
        else:
            cmds.append(f"print (int)&((struct DwPuzzleDebug*)0)->{field}")
    proc = subprocess.run(
        ["gdb", "-batch", str(NEF)] + [x for c in cmds for x in ("-ex", c)],
        capture_output=True, text=True, timeout=300)
    vals = re.findall(r"^\$(\d+) = (-?\d+)", proc.stdout, re.M)
    if len(vals) != len(FIELDS):
        raise RuntimeError(
            f"gdb returned {len(vals)} offsets, want {len(FIELDS)}:\n{proc.stdout}\n{proc.stderr}")
    out = {}
    for (key, _field), (_n, val) in zip(FIELDS, vals):
        out[key] = int(val)
    return out


def generate():
    if not NEF.exists():
        raise RuntimeError(f"{NEF} missing: run `make release` first")
    data = _gdb_offsets()
    data["_note"] = (
        "Generated by gen_debug_offsets.py from build/main.nef DWARF. "
        "Do not hand-edit: regenerate after any change to DwPuzzleDebug.")
    data["_dw_puzzle_h_sha256"] = hashlib.sha256(HEADER.read_bytes()).hexdigest()
    return data


def main():
    check = "--check" in sys.argv
    data = generate()
    if check:
        old = json.loads(OUT.read_text())
        if old != data:
            print(f"dw_debug_offsets.json is stale: regenerate with:\n  {sys.argv[0]}")
            print(f"checked-in: {old}\nregenerated: {data}")
            return 1
        print("dw_debug_offsets.json matches build/main.nef DWARF")
        return 0
    OUT.write_text(json.dumps(data, indent=1, sort_keys=True) + "\n")
    print(f"wrote {OUT} ({len(data)} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
