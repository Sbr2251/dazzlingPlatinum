#!/usr/bin/env python3
"""Convert BW2's ability pop-up banner art into the C arrays src/battle/ability_popup.c uses.

    tools/battle_events/make_ability_banner.py [OUT]   (default: src/battle/ability_popup_banner.h)

Source (asset policy: BW2 assets are allowed for battle visuals, see /tmp/bw2vis/COMMON.md):
    res/battle/ability_popup/bw2_ability_banner_483.png   pokebw2 res/graphics/btlv/483.png (a/0/1/1 file 0x1E3,
                                                          the characters of BtlvScuAbilityWin, btlv_scu.c:2512)
    res/battle/ability_popup/bw2_ability_banner_484.pal   pokebw2 res/graphics/btlv/484.pal (file 0x1E4, loaded to
                                                          BG palettes 1-3, btlv_scu.c:411; the banners use palette 1)
both copied from pokebw2 @ df7fa79a0.

The PNG is the NCGR drawn 18 tiles wide: tile rows 0-3 are the player-side banner (bar on the left, chevron on
the right), tile rows 4-7 the foe-side banner (chevron on the left). Each banner becomes 18x4 4bpp tiles in
row-major order, the layout of a Window's pixel buffer (and of BW2's 18x4 GFL bitmap). Pure Python: no PIL.
"""

import pathlib
import struct
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
PNG = ROOT / "res/battle/ability_popup/bw2_ability_banner_483.png"
PAL = ROOT / "res/battle/ability_popup/bw2_ability_banner_484.pal"
OUT = ROOT / "src/battle/ability_popup_banner.h"

TILES_X = 18
TILES_Y = 4
PALETTE_INDEX = 1  # BG palette 1 of file 0x1E4


def read_png_indexed(path):
    data = path.read_bytes()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    pos = 8
    width = height = None
    idat = b""
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if kind == b"IHDR":
            width, height, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", body)
            assert depth == 8 and color == 3 and interlace == 0, "expected an 8-bit indexed, non-interlaced PNG"
        elif kind == b"IDAT":
            idat += body
        elif kind == b"IEND":
            break
    raw = zlib.decompress(idat)
    rows = []
    prev = bytearray(width)
    stride = width + 1
    for y in range(height):
        ftype = raw[y * stride]
        line = bytearray(raw[y * stride + 1:(y + 1) * stride])
        for x in range(width):
            a = line[x - 1] if x else 0
            b = prev[x]
            c = prev[x - 1] if x else 0
            if ftype == 1:
                line[x] = (line[x] + a) & 0xFF
            elif ftype == 2:
                line[x] = (line[x] + b) & 0xFF
            elif ftype == 3:
                line[x] = (line[x] + ((a + b) >> 1)) & 0xFF
            elif ftype == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pred = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[x] = (line[x] + pred) & 0xFF
        rows.append(bytes(line))
        prev = line
    return width, height, rows


def read_jasc(path):
    lines = path.read_text().split()
    assert lines[0] == "JASC-PAL"
    count = int(lines[2])
    vals = list(map(int, lines[3:3 + count * 3]))
    return [tuple(vals[i * 3:i * 3 + 3]) for i in range(count)]


def tiles_for(rows, tile_y0):
    out = bytearray()
    for ty in range(TILES_Y):
        for tx in range(TILES_X):
            for py in range(8):
                row = rows[(tile_y0 + ty) * 8 + py]
                for px in range(0, 8, 2):
                    lo = row[tx * 8 + px] & 0xF
                    hi = row[tx * 8 + px + 1] & 0xF
                    out.append(lo | (hi << 4))
    return out


def c_bytes(name, data):
    lines = [f"static const u8 {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    width, height, rows = read_png_indexed(PNG)
    assert (width, height) == (TILES_X * 8, TILES_Y * 8 * 2), (width, height)
    colors = read_jasc(PAL)[PALETTE_INDEX * 16:(PALETTE_INDEX + 1) * 16]
    bgr555 = [((r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)) for r, g, b in colors]

    text = [
        "// Generated by tools/battle_events/make_ability_banner.py from BW2's ability pop-up art",
        "// (pokebw2 @ df7fa79a0, res/graphics/btlv/483.png and 484.pal). Do not edit by hand.",
        "",
        "#define ABILITY_BANNER_TILES_X " + str(TILES_X),
        "#define ABILITY_BANNER_TILES_Y " + str(TILES_Y),
        "",
        c_bytes("sAbilityBannerTiles_Player", tiles_for(rows, 0)),
        "",
        c_bytes("sAbilityBannerTiles_Enemy", tiles_for(rows, TILES_Y)),
        "",
        "static const u16 sAbilityBannerPalette[16] = {",
        "    " + ", ".join(f"0x{c:04X}" for c in bgr555[:8]) + ",",
        "    " + ", ".join(f"0x{c:04X}" for c in bgr555[8:]) + ",",
        "};",
        "",
    ]
    out.write_text("\n".join(text))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
