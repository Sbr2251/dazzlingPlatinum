#!/usr/bin/env python3
"""Generate headless_names.{h,c}: symbolic name -> id tables for the headless protocol.

Sources are the build's own generated data (nothing hand-maintained):
  generated/map_headers.txt, generated/vars_flags.txt, generated/items.txt,
  generated/species.txt  (the metang enum sources; `NAME = ALIAS` resolved here)
  res/field/maps/*/events.json  (LOCALID_* per map; map dir -> MAP_HEADER_<DIR>)
  include/constants/map_object.h (DIR_* facing constants)

Usage: gen_headless_names.py <repo_root> <out_dir>
Writes <out_dir>/headless_names.h and <out_dir>/headless_names.c.
"""
import json
import os
import re
import sys


def parse_enum_txt(path):
    """metang enum txt: sequential values, `NAME = ALIAS|number` overrides."""
    values = {}
    order = []
    nxt = 0
    for raw in open(path):
        line = raw.split("#")[0].strip()
        if not line:
            continue
        if "=" in line:
            name, _, rhs = line.partition("=")
            name, rhs = name.strip(), rhs.strip()
            if rhs.lstrip("-").isdigit():
                val = int(rhs, 0)
            elif rhs in values:
                val = values[rhs]
            else:
                continue  # alias to something outside this file; skip
        else:
            name, val = line, nxt
        values[name] = val
        order.append((name, val))
        nxt = val + 1
    return order


def main():
    root, outdir = sys.argv[1], sys.argv[2]
    os.makedirs(outdir, exist_ok=True)

    tables = {
        "MapHeaders": parse_enum_txt(os.path.join(root, "generated/map_headers.txt")),
        "Items": parse_enum_txt(os.path.join(root, "generated/items.txt")),
        "Species": parse_enum_txt(os.path.join(root, "generated/species.txt")),
        "Moves": parse_enum_txt(os.path.join(root, "generated/moves.txt")),
        "Abilities": parse_enum_txt(os.path.join(root, "generated/abilities.txt")),
        "Natures": parse_enum_txt(os.path.join(root, "generated/natures.txt")),
    }
    varflag = parse_enum_txt(os.path.join(root, "generated/vars_flags.txt"))
    tables["Vars"] = [(n, v) for n, v in varflag if n.startswith("VAR_")]
    tables["Flags"] = [(n, v) for n, v in varflag if n.startswith("FLAG_")]

    # DIR_* from the constants header (facing directions used by warp/talk).
    dirs = []
    for line in open(os.path.join(root, "include/constants/map_object.h")):
        m = re.match(r"#define\s+(DIR_\w+)\s+(-?\d+)\s*$", line.strip())
        if m:
            dirs.append((m.group(1), int(m.group(2))))
    tables["Dirs"] = dirs

    # LOCALID_* per map header, from each map's events.json (object order = local id).
    locals_rows = []
    maps_dir = os.path.join(root, "res/field/maps")
    header_ids = dict(tables["MapHeaders"])
    for entry in sorted(os.listdir(maps_dir)):
        ev_path = os.path.join(maps_dir, entry, "events.json")
        if not os.path.isfile(ev_path):
            continue
        header = "MAP_HEADER_" + entry.upper()
        if header not in header_ids:
            continue
        try:
            data = json.load(open(ev_path))
        except Exception:
            continue
        for idx, obj in enumerate(data.get("object_events", [])):
            name = obj.get("id", "")
            if name.startswith("LOCALID_"):
                locals_rows.append((header_ids[header], name, idx))

    with open(os.path.join(outdir, "headless_names.h"), "w") as f:
        f.write("/* Generated by tools/dazzling/gen_headless_names.py - do not edit. */\n")
        f.write("#pragma once\ntypedef struct { const char *name; int id; } HeadlessName;\n")
        f.write("typedef struct { int mapHeader; const char *name; int localId; } HeadlessLocal;\n")
        for key in tables:
            f.write("extern const HeadlessName kHeadless%s[]; extern const int kHeadless%sCount;\n" % (key, key))
        f.write("extern const HeadlessLocal kHeadlessLocals[]; extern const int kHeadlessLocalsCount;\n")
        f.write("const HeadlessName *Headless_Lookup(const HeadlessName *table, int count, const char *name);\n")
        f.write("const char *Headless_NameOf(const HeadlessName *table, int count, int id);\n")

    with open(os.path.join(outdir, "headless_names.c"), "w") as f:
        f.write("/* Generated by tools/dazzling/gen_headless_names.py - do not edit. */\n")
        f.write('#include "headless_names.h"\n#include <string.h>\n')
        for key, rows in tables.items():
            f.write("const HeadlessName kHeadless%s[] = {" % key)
            f.write(",".join('{"%s",%d}' % (n, v) for n, v in rows))
            f.write("};\nconst int kHeadless%sCount = %d;\n" % (key, len(rows)))
        f.write("const HeadlessLocal kHeadlessLocals[] = {")
        f.write(",".join('{%d,"%s",%d}' % r for r in locals_rows))
        f.write("};\nconst int kHeadlessLocalsCount = %d;\n" % len(locals_rows))
        f.write(
            "const HeadlessName *Headless_Lookup(const HeadlessName *t, int c, const char *n) {"
            " for (int i = 0; i < c; i++) if (strcmp(t[i].name, n) == 0) return &t[i]; return 0; }\n"
            "const char *Headless_NameOf(const HeadlessName *t, int c, int id) {"
            " for (int i = 0; i < c; i++) if (t[i].id == id) return t[i].name; return 0; }\n"
        )
    print("headless_names: %s, locals=%d" % ({k: len(v) for k, v in tables.items()}, len(locals_rows)))


if __name__ == "__main__":
    main()
